#!/usr/bin/env python3
"""Generates the mss32.dll proxy forwarding from loader/mss32-exports.txt (the real DLL's export names):
loader/mss32_thunks.S (one jmp per export), loader/mss32_names.h, loader/mss32.def."""
import os
here = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'loader')
names = [l.strip() for l in open(os.path.join(here, 'mss32-exports.txt')) if l.strip()]
asm = ['/* generated by tools/gen_mss32.py: one jump per mss32.dll export, through onc_mss_ptrs[] */',
       '.intel_syntax noprefix', '.text']
for i, n in enumerate(names):
    asm += [f'.globl _onc_mss_{i}', f'_onc_mss_{i}:', f'    jmp DWORD PTR [_onc_mss_ptrs+{4*i}]']
open(os.path.join(here, 'mss32_thunks.S'), 'w').write('\n'.join(asm) + '\n')
c = ['/* generated by tools/gen_mss32.py: the real mss32.dll exports, in thunk order */',
     f'#define ONC_MSS_COUNT {len(names)}', 'static const char *const onc_mss_names[ONC_MSS_COUNT] = {']
c += [f'    "{n}",' for n in names] + ['};']
open(os.path.join(here, 'mss32_names.h'), 'w').write('\n'.join(c) + '\n')
d = ['LIBRARY mss32.dll', 'EXPORTS'] + [f'    "{n}" = onc_mss_{i}' for i, n in enumerate(names)]
open(os.path.join(here, 'mss32.def'), 'w').write('\n'.join(d) + '\n')
